local function attribute_name(capability_id)
  if ATTRIBUTE_OVERRIDES[capability_id] ~= nil then
    return ATTRIBUTE_OVERRIDES[capability_id]
  end

  return (capability_id:gsub("%d", DIGIT_WORDS))
end

local function titleize(value)
  local label = value:gsub("(%l)(%u)", "%1 %2"):gsub("2ct", "2CT"):gsub("Ph", "pH"):gsub("Orp", "ORP"):gsub("Tds", "TDS")
  return label:sub(1, 1):upper() .. label:sub(2)
end
local function command_name(attr, writable) return writable and ("set" .. capitalize(attr)) or nil end
local function base_metadata(row, kind)
  local capability_id, writable, mapping_name = row[1], row[2], row[3]
  local attr = attribute_name(capability_id)
  return { emit_name = capability_id, capability_id = CAPABILITY_NAMESPACE .. capability_id, attribute_name = attr, command_name = command_name(attr, writable), argument_name = writable and attr or nil, mapping_name = mapping_name, label = titleize(capability_id), kind = kind }
end
local function numeric(row)
  local metadata = base_metadata(row, "numeric")
  metadata.default_range = { minimum = row[4], maximum = row[5], step = row[6], unit = row[7] }
  metadata.event_unit = row[7]
  return metadata
end
local function enum(row)
  local metadata = base_metadata(row, "enum")
  metadata.supported_values = row[4]
  metadata.default_range = { allowed_values = row[4] }
  return metadata
end
local function text(row)
  local metadata = base_metadata(row, "text")
  metadata.maximum_length = row[4]
  return metadata
end
local function build(rows, factory)
  local definitions = {}
  for _, row in ipairs(rows) do definitions[#definitions + 1] = factory(row) end
  return definitions
end
